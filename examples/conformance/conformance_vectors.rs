//! Generate the cross-language conformance corpus for the SACI Arrow IPC wire
//! format.
//!
//! ```bash
//! cargo run -p saci-service --features conformance --example conformance_vectors -- emit
//! ```
//!
//! Output lands in `packages/arrow-ipc-conformance/`: one `manifest.json` and
//! one `.saci` file per case. Every codec under `packages/arrow-ipc-*` runs the
//! corpus, so the five agree on exactly which streams are valid and which are
//! not.
//!
//! # How the malformed vectors are made
//!
//! Each one is a surgical mutation of a real `Dataset::write_ipc` stream, not a
//! hand-forged flatbuffer. A hand-forged stream can drift from what arrow-rs
//! actually emits, and then a codec that rejects it looks correct while failing
//! on real traffic. Mutating real output keeps every vector one edit away from a
//! stream the reference writer produced.
//!
//! The one exception is `compressed_batch`, which is re-encoded through
//! arrow-rs with LZ4 enabled. That needs the `conformance` feature, which turns
//! on `arrow-ipc/lz4` here and nowhere else: a normal SACI build cannot write a
//! compressed batch, and must reject one.
//!
//! # Reason codes
//!
//! A rejected case carries a language-neutral `reason`. Error text differs by
//! language on purpose, so a codec's harness maps the reason to whatever
//! substring its own message uses. The reason set is the contract; the wording
//! is local.

