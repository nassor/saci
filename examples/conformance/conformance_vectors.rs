const GENERATED_BY: &str = "@generated by `cargo run -p saci-service --features conformance --example conformance_vectors -- emit`";

/// Arrow `MessageHeader` union discriminants.
const HEADER_SCHEMA: u8 = 1;
const HEADER_DICTIONARY_BATCH: u8 = 2;
const HEADER_RECORD_BATCH: u8 = 3;

// ---------------------------------------------------------------------------
// the Order component
//
// Every vector is a mutation of a real `Dataset::write_ipc` stream of this
// component, so these twelve fields are the shape each codec under
// `packages/arrow-ipc-*` decodes when it runs the corpus. Field order is
// load-bearing twice over: it feeds the schema fingerprint recorded in the
// manifest, and it fixes the node and buffer order the mutations below index
// into.
//
// The definition is inlined rather than shared with the polyglot example. The
// corpus is checked in, so the generator has to build on its own; a schema
// crate it depended on would make regenerating the corpus contingent on that
// crate existing.
// ---------------------------------------------------------------------------

/// One order, in the shape the conformance corpus carries.
#[derive(serde::Serialize, serde::Deserialize, Clone, Debug, PartialEq)]
pub struct Order {
    /// Stable row identity.
    pub id: i64,
    /// Originating region (`emea` / `apac` / `amer`).
    pub region: String,
    /// ISO currency code of `amount`.
    pub currency: String,
    /// Order amount in `currency`.
    pub amount: f64,
    /// Whether the order passed validation.
    pub valid: bool,
    /// `amount` converted to USD, or `0.0` when invalid.
    pub usd_amount: f64,
    /// `usd_amount` rendered for display. The second variable-width column,
    /// and the reason the `variable_width_write` vector has a sibling type to
    /// address.
    pub usd_amount_display: String,
    /// `usd_amount / risk_threshold`.
    pub risk_score: f64,
    /// `risk_score >= 1.0`.
    pub flagged: bool,
    /// `usd_amount` times the region's rate, or `0.0` when invalid.
    pub fee: f64,
    /// `0` clear, `1` manual review, `2` escalated.
    pub review_tier: i64,
    /// `REJECTED` / `HOLD` / `REVIEW` / `SETTLED`.
    pub settlement: String,
}

impl Component for Order {
    fn name() -> &'static str {
        "Order"
    }

    fn schema() -> Arc<Schema> {
        Arc::new(Schema::new(vec![
            Field::new("id", DataType::Int64, false),
            Field::new("region", DataType::Utf8, false),
            Field::new("currency", DataType::Utf8, false),
            Field::new("amount", DataType::Float64, false),
            Field::new("valid", DataType::Boolean, false),
            Field::new("usd_amount", DataType::Float64, false),
            Field::new("usd_amount_display", DataType::Utf8, false),
            Field::new("risk_score", DataType::Float64, false),
            Field::new("flagged", DataType::Boolean, false),
            Field::new("fee", DataType::Float64, false),
            Field::new("review_tier", DataType::Int64, false),
            Field::new("settlement", DataType::Utf8, false),
        ]))
    }
}

impl Order {
    /// An input row with every derived column zeroed.
    fn seed(id: i64, region: &str, currency: &str, amount: f64) -> Self {
        Self {
            id,
            region: region.to_string(),
            currency: currency.to_string(),
            amount,
            valid: false,
            usd_amount: 0.0,
            usd_amount_display: String::new(),
            risk_score: 0.0,
            flagged: false,
            fee: 0.0,
            review_tier: 0,
            settlement: String::new(),
        }
    }
}

/// The six rows the baseline vector carries.
