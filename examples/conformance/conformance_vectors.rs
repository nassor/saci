// ---------------------------------------------------------------------------
// flatbuffer navigation
//
// Only enough to find a value and overwrite it in place. Every helper returns
// an absolute offset into the slice it was handed.
// ---------------------------------------------------------------------------

/// Follow the root uoffset at `at` to the table it points at.
fn root_table(buf: &[u8], at: usize) -> usize {
    let rel = i32::from_le_bytes(buf[at..at + 4].try_into().unwrap());
    at + rel as usize
}

/// Absolute offset of `table`'s vtable.
fn vtable(buf: &[u8], table: usize) -> usize {
    let back = i32::from_le_bytes(buf[table..table + 4].try_into().unwrap());
    table - back as usize
}

/// Absolute offset of field `id`'s value inside `table`, or `None` when the
/// field is absent.
fn field(buf: &[u8], table: usize, id: usize) -> Option<usize> {
    let vt = vtable(buf, table);
    let vt_len = u16::from_le_bytes(buf[vt..vt + 2].try_into().unwrap()) as usize;
    let slot = 4 + id * 2;
    if slot + 2 > vt_len {
        return None;
    }
    let rel = u16::from_le_bytes(buf[vt + slot..vt + slot + 2].try_into().unwrap()) as usize;
    if rel == 0 { None } else { Some(table + rel) }
}

/// Resolve a vector field to `(element_start, count)`.
fn vector(buf: &[u8], table: usize, id: usize) -> Option<(usize, usize)> {
    let at = field(buf, table, id)?;
    let rel = u32::from_le_bytes(buf[at..at + 4].try_into().unwrap()) as usize;
    let vec_at = at + rel;
    let count = u32::from_le_bytes(buf[vec_at..vec_at + 4].try_into().unwrap()) as usize;
    Some((vec_at + 4, count))
}

/// One Arrow IPC message inside a segment.
struct Message {
    /// Offset of the continuation marker, relative to the segment body.
    start: usize,
    body_len: i64,
    header_type: u8,
    /// Offset of the message table, relative to the segment body.
    table: usize,
    /// Offset just past this message, relative to the segment body.
    end: usize,
}

/// One length-prefixed segment.
struct Segment {
    /// Offset of the u32 length prefix, absolute in the stream.
    prefix: usize,
    /// Offset of the segment body, absolute in the stream.
    body: usize,
    len: usize,
    messages: Vec<Message>,
}

fn align8(n: i64) -> usize {
    ((n + 7) & !7) as usize
}

/// Walk the stream into segments and their messages.
fn parse_framing(stream: &[u8]) -> Vec<Segment> {
    let mut segments = Vec::new();
    let mut pos = 0usize;

    loop {
        let len = u32::from_le_bytes(stream[pos..pos + 4].try_into().unwrap()) as usize;
        if len == 0 {
            break;
        }
        let body = pos + 4;
        let seg = &stream[body..body + len];

        let mut messages = Vec::new();
        let mut mp = 0usize;
        while mp + 8 <= seg.len() {
            let cont = u32::from_le_bytes(seg[mp..mp + 4].try_into().unwrap());
            assert_eq!(cont, 0xFFFF_FFFF, "expected a continuation marker at {mp}");
            let metadata_len = u32::from_le_bytes(seg[mp + 4..mp + 8].try_into().unwrap()) as usize;
            if metadata_len == 0 {
                // End-of-stream marker.
                mp += 8;
                continue;
            }
            let meta_start = mp + 8;
            let table = root_table(seg, meta_start);
            let header_type = field(seg, table, 1).map_or(0, |at| seg[at]);
            let body_len = field(seg, table, 3).map_or(0, |at| {
                i64::from_le_bytes(seg[at..at + 8].try_into().unwrap())
            });
            let end = meta_start + metadata_len + align8(body_len);
            messages.push(Message {
                start: mp,
                body_len,
                header_type,
                table,
                end,
            });
            mp = end;
        }

        segments.push(Segment {
            prefix: pos,
            body,
            len,
            messages,
        });
        pos = body + len;
    }

    segments
}

/// The `RecordBatch` header table of a message, relative to the segment body.
fn record_batch_table(seg: &[u8], message: &Message) -> usize {
    let header_at = field(seg, message.table, 2).expect("Message.header is required");
    let rel = u32::from_le_bytes(seg[header_at..header_at + 4].try_into().unwrap()) as usize;
    header_at + rel
}

